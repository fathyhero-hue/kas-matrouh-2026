      ('public.admin_audit_logs', 'request_id', 'text', false),
      ('public.admin_audit_logs', 'ip_hash', 'text', false),
      ('public.admin_audit_logs', 'user_agent', 'text', false),
      ('public.admin_audit_logs', 'created_at', 'timestamp with time zone', true)
    ) as expected(table_name, column_name, type_name, not_null)
  loop
    select format_type(a.atttypid, a.atttypmod), a.attnotnull
    into actual_type, actual_not_null
    from pg_attribute a
    where a.attrelid = to_regclass(v.table_name)
      and a.attname = v.column_name
      and a.attnum > 0
      and not a.attisdropped;

    if not found
       or actual_type <> v.type_name
       or (v.not_null is not null and actual_not_null <> v.not_null) then
      raise exception 'RBAC post-DDL validation failed: incompatible column %.%', v.table_name, v.column_name;
    end if;
  end loop;

  for v in
    select * from (values
