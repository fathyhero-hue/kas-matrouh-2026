  from pg_attribute a
  where a.attrelid = 'public.admin_audit_logs'::regclass
    and a.attname = 'id'
    and a.attnum > 0
    and not a.attisdropped;

  if actual_identity <> 'd' then
    raise exception 'RBAC post-DDL validation failed: admin_audit_logs.id must be GENERATED BY DEFAULT AS IDENTITY';
  end if;

