      ('public.admin_role_permissions', 'permission_key', 'text', true),
      ('public.admin_permission_overrides', 'user_id', 'uuid', true),
      ('public.admin_permission_overrides', 'permission_key', 'text', true),
      ('public.admin_permission_overrides', 'effect', 'text', true),
      ('public.admin_permission_overrides', 'created_at', 'timestamp with time zone', true),
