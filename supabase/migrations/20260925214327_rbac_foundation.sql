    if primary_key_count <> 1 or actual_key_columns is distinct from v.key_columns then
      raise exception 'RBAC post-DDL validation failed: incompatible primary key on %', v.table_name;
    end if;
  end loop;

  for v in
    select * from (values
      ('public.admin_role_permissions', 'role_key', 'public.admin_roles', 'key', 'c'),
      ('public.admin_role_permissions', 'permission_key', 'public.admin_permissions', 'key', 'c'),
      ('public.admin_permission_overrides', 'user_id', 'auth.users', 'id', 'c'),
      ('public.admin_permission_overrides', 'permission_key', 'public.admin_permissions', 'key', 'c'),
      ('public.admin_audit_logs', 'actor_user_id', 'auth.users', 'id', 'n')
