do $$
declare
  role_count integer;
  permission_count integer;
  super_admin_permission_count integer;
begin
  select count(*) into role_count from public.admin_roles;
  select count(*) into permission_count from public.admin_permissions;

  if role_count <> 8 or permission_count <> 56 then
    raise exception 'RBAC seed validation failed: expected 8 roles and 56 permissions, found % roles and % permissions', role_count, permission_count;
  end if;

  select count(*) into super_admin_permission_count
  from public.admin_role_permissions rp
  join public.admin_permissions p on p.key = rp.permission_key
  where rp.role_key = 'super_admin';

  if super_admin_permission_count <> permission_count then
    raise exception 'RBAC seed validation failed: super_admin must have every catalog permission';
  end if;

  if exists (
    select 1
    from public.admin_role_permissions rp
    where rp.role_key = 'supervisor'
      and rp.permission_key in (
        'admins.create', 'admins.edit', 'admins.disable', 'admins.reset_password',
        'admins.permissions.manage', 'settings.manage', 'shop.orders.financial.manage'
      )
  ) then
    raise exception 'RBAC seed validation failed: supervisor has a forbidden permission';
  end if;
end
$$;

