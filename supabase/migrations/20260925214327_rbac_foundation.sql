      and position('allow' in pg_get_constraintdef(c.oid)) > 0
      and position('deny' in pg_get_constraintdef(c.oid)) > 0
  ) then
    raise exception 'RBAC post-DDL validation failed: missing allow/deny constraint';
  end if;
end
