    from pg_constraint c
    join pg_attribute source_column
      on source_column.attrelid = c.conrelid and source_column.attname = v.source_column
    join pg_attribute target_column
      on target_column.attrelid = c.confrelid and target_column.attname = v.target_column
    where c.conrelid = to_regclass(v.source_table)
      and c.contype = 'f'
      and c.conkey = array[source_column.attnum]::smallint[]
      and c.confrelid = to_regclass(v.target_table)
      and c.confkey = array[target_column.attnum]::smallint[]
      and c.confdeltype = v.delete_action
      and c.convalidated;

    if exact_foreign_key_count <> 1 then
      raise exception 'RBAC post-DDL validation failed: incompatible foreign key on %.%', v.source_table, v.source_column;
    end if;
  end loop;

  if not exists (
    select 1
    from pg_constraint c
    join pg_attribute a on a.attrelid = c.conrelid and a.attname = 'effect'
    where c.conrelid = 'public.admin_permission_overrides'::regclass
      and c.contype = 'c'
