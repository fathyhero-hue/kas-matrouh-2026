-- RBAC foundation for admin accounts.
-- Review and execute only after the confirmed Production project is selected.
-- This migration is intentionally additive and keeps admin_profiles.role for compatibility.

-- Fail before creating RBAC objects if the verified bootstrap identity has drifted.
do $$
declare
  bootstrap_user_id constant uuid := '2dfd1ab1-1fe2-4024-91bc-b17103f524be';
  auth_user_count integer;
  profile_count integer;
  profile_role text;
  profile_name text;
  profile_role_key text;
  profile_is_active text;
begin
  select count(*) into auth_user_count
  from auth.users
  where id = bootstrap_user_id;

  if auth_user_count <> 1 then
    raise exception 'RBAC preflight aborted: expected exactly one verified Auth user, found %', auth_user_count;
  end if;

  select count(*) into profile_count
  from public.admin_profiles
  where user_id = bootstrap_user_id;

  if profile_count <> 1 then
    raise exception 'RBAC preflight aborted: expected exactly one admin profile for the verified Auth user, found %', profile_count;
  end if;

  select p.role, p.display_name, to_jsonb(p)->>'role_key', to_jsonb(p)->>'is_active'
  into profile_role, profile_name, profile_role_key, profile_is_active
  from public.admin_profiles p
  where p.user_id = bootstrap_user_id;

  if lower(trim(coalesce(profile_name, ''))) <> 'fathy'
     or lower(trim(coalesce(profile_role, ''))) <> 'admin' then
    raise exception 'RBAC preflight aborted: verified profile is not the expected legacy admin';
  end if;

  if profile_role_key is not null and profile_role_key <> 'super_admin' then
    raise exception 'RBAC preflight aborted: verified profile already has a conflicting role_key';
  end if;

  if profile_is_active = 'false' then
    raise exception 'RBAC preflight aborted: verified profile is already inactive';
  end if;
end
$$;

-- Validate only legacy prerequisites before DDL. Fresh installs may have none of
-- the RBAC tables yet, so optional RBAC objects are inspected through catalogs.
do $$
declare
  rbac_table_count integer;
  existing_rbac_tables text;
begin
  select count(*), string_agg(c.relname, ', ' order by c.relname)
  into rbac_table_count, existing_rbac_tables
  from pg_class c
  join pg_namespace n on n.oid = c.relnamespace
  where n.nspname = 'public'
    and c.relkind in ('r', 'p')
    and c.relname in (
      'admin_roles', 'admin_permissions', 'admin_role_permissions',
      'admin_permission_overrides', 'admin_audit_logs'
    );

  if rbac_table_count <> 0 then
    raise exception 'RBAC preflight aborted: partial RBAC state detected (% of 5 tables: %)',
      rbac_table_count, existing_rbac_tables;
  end if;
end
$$;

create table if not exists public.admin_roles (
  key text primary key,
  name text not null,
  description text,
  is_system boolean not null default true,
  created_at timestamptz not null default now()
);

create table if not exists public.admin_permissions (
  key text primary key,
  name text not null,
  description text,
  created_at timestamptz not null default now()
);

create table if not exists public.admin_role_permissions (
  role_key text not null references public.admin_roles(key) on delete cascade,
  permission_key text not null references public.admin_permissions(key) on delete cascade,
  primary key (role_key, permission_key)
);

create table if not exists public.admin_permission_overrides (
  -- Overrides are per-user dependent data; audit history uses SET NULL and is retained.
  user_id uuid not null references auth.users(id) on delete cascade,
  permission_key text not null references public.admin_permissions(key) on delete cascade,
  effect text not null check (effect in ('allow', 'deny')),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  primary key (user_id, permission_key)
);

create table if not exists public.admin_audit_logs (
  id bigint generated by default as identity primary key,
  actor_user_id uuid references auth.users(id) on delete set null,
  action text not null,
  permission_key text,
  entity_type text,
  entity_id text,
  metadata jsonb not null default '{}'::jsonb,
  request_id text,
  ip_hash text,
  user_agent text,
  created_at timestamptz not null default now()
);

alter table public.admin_profiles add column if not exists role_key text;
alter table public.admin_profiles add column if not exists is_active boolean not null default true;
alter table public.admin_profiles add column if not exists last_login_at timestamptz;
alter table public.admin_profiles add column if not exists created_by uuid;
alter table public.admin_profiles add column if not exists updated_at timestamptz not null default now();

do $$
declare
  v record;
  foreign_key_count integer;
  exact_foreign_key_count integer;
begin
  for v in
    select * from (values
      ('role_key', 'public.admin_roles', 'key', 'r', 'admin_profiles_role_key_fkey'),
      ('created_by', 'auth.users', 'id', 'n', 'admin_profiles_created_by_fkey'),
      ('user_id', 'auth.users', 'id', 'r', 'admin_profiles_user_id_fkey')
    ) as expected(source_column, target_table, target_column, delete_action, constraint_name)
  loop
    select count(*) into foreign_key_count
    from pg_constraint c
    join pg_attribute source_column
      on source_column.attrelid = c.conrelid and source_column.attname = v.source_column
    where c.conrelid = 'public.admin_profiles'::regclass
      and c.contype = 'f'
      and source_column.attnum = any(c.conkey);

    select count(*) into exact_foreign_key_count
    from pg_constraint c
    join pg_attribute source_column
      on source_column.attrelid = c.conrelid and source_column.attname = v.source_column
    join pg_attribute target_column
      on target_column.attrelid = c.confrelid and target_column.attname = v.target_column
    where c.conrelid = 'public.admin_profiles'::regclass
      and c.contype = 'f'
      and c.conkey = array[source_column.attnum]::smallint[]
      and c.confrelid = to_regclass(v.target_table)
      and c.confkey = array[target_column.attnum]::smallint[]
      and (v.source_column = 'user_id' or c.confdeltype = v.delete_action)
      and c.convalidated;

    if foreign_key_count = 0 then
      execute format(
        'alter table public.admin_profiles add constraint %I foreign key (%I) references %s(%I) on delete %s',
        v.constraint_name,
        v.source_column,
        v.target_table,
        v.target_column,
        case v.delete_action when 'r' then 'restrict' when 'n' then 'set null' end
      );
    elsif foreign_key_count <> 1 or exact_foreign_key_count <> 1 then
      raise exception 'RBAC schema preflight aborted: conflicting foreign key on admin_profiles.%', v.source_column;
    end if;
  end loop;
end
$$;

