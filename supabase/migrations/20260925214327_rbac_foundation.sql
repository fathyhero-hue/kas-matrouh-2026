do $$
declare
  v record;
  index_definition text;
begin
  for v in
    select * from (values
      ('admin_profiles_role_key_idx', 'admin_profiles', 'role_key'),
      ('admin_profiles_is_active_idx', 'admin_profiles', 'is_active'),
      ('admin_permission_overrides_permission_idx', 'admin_permission_overrides', 'permission_key'),
      ('admin_audit_logs_actor_created_idx', 'admin_audit_logs', 'actor_user_id,created_atdesc'),
      ('admin_audit_logs_entity_idx', 'admin_audit_logs', 'entity_type,entity_id,created_atdesc')
    ) as expected(index_name, table_name, key_definition)
  loop
    if to_regclass('public.' || v.index_name) is null then
      raise exception 'RBAC index validation failed: index % is missing', v.index_name;
    end if;

    select lower(regexp_replace(pg_get_indexdef(i.indexrelid), '[[:space:]]', '', 'g'))
    into index_definition
    from pg_index i
    where i.indexrelid = to_regclass('public.' || v.index_name)
      and i.indrelid = to_regclass('public.' || v.table_name)
      and i.indisvalid
      and not i.indisunique
      and i.indpred is null
      and i.indexprs is null;

    if index_definition is null
       or position('onpublic.' || v.table_name || 'usingbtree(' || v.key_definition || ')' in index_definition) = 0 then
      raise exception 'RBAC index validation failed: incompatible definition for index %', v.index_name;
    end if;
  end loop;
end
$$;

-- Bootstrap only the confirmed existing account. Abort instead of guessing if the
-- legacy profile shape is not exactly the expected single Fathy admin profile.
do $$
declare
  bootstrap_user_id constant uuid := '2dfd1ab1-1fe2-4024-91bc-b17103f524be';
  auth_user_count integer;
  profile_count integer;
begin
  select count(*) into profile_count
  from public.admin_profiles
  where user_id = bootstrap_user_id
    and lower(trim(display_name)) = 'fathy'
    and lower(trim(role)) = 'admin';

  if profile_count <> 1 then
    raise exception 'RBAC bootstrap aborted: confirmed admin profile did not match the expected identity; found %', profile_count;
  end if;

  if exists (
    select 1 from public.admin_profiles
    where user_id = bootstrap_user_id
      and lower(trim(display_name)) = 'fathy'
      and lower(trim(role)) = 'admin'
      and role_key is null
  ) then
    update public.admin_profiles
    set role_key = 'super_admin',
        is_active = true,
        updated_at = now()
    where role_key is null
      and user_id = bootstrap_user_id
      and lower(trim(display_name)) = 'fathy'
      and lower(trim(role)) = 'admin';
  elsif not exists (
    select 1 from public.admin_profiles
    where user_id = bootstrap_user_id
      and lower(trim(display_name)) = 'fathy'
      and lower(trim(role)) = 'admin'
      and role_key = 'super_admin'
      and is_active = true
  ) then
    raise exception 'RBAC bootstrap aborted: Fathy already has a conflicting role or inactive status';
  end if;

  select count(*) into auth_user_count
  from auth.users
  where id = bootstrap_user_id;

  select count(*) into profile_count
  from public.admin_profiles
  where user_id = bootstrap_user_id
    and lower(trim(display_name)) = 'fathy'
    and lower(trim(role)) = 'admin'
    and role_key = 'super_admin'
    and is_active = true;

  if auth_user_count <> 1 or profile_count <> 1 then
    raise exception 'RBAC bootstrap aborted: expected one verified Auth user and one active super_admin profile; found % Auth users and % profiles', auth_user_count, profile_count;
  end if;
end
$$;

-- RLS is enabled on the new RBAC tables with no client policies, so they remain
-- service-role-only. Do not change admin_profiles RLS or existing policies here:
-- their Production state was not available for read-only inspection.
alter table public.admin_roles enable row level security;
alter table public.admin_permissions enable row level security;
alter table public.admin_role_permissions enable row level security;
alter table public.admin_permission_overrides enable row level security;
alter table public.admin_audit_logs enable row level security;

do $$
begin
  if exists (
    select 1
    from pg_class c
    join pg_namespace n on n.oid = c.relnamespace
    where n.nspname = 'public'
      and c.relname in (
        'admin_roles', 'admin_permissions', 'admin_role_permissions',
        'admin_permission_overrides', 'admin_audit_logs'
      )
      and not c.relrowsecurity
  ) then
    raise exception 'RBAC RLS validation failed: row-level security is not enabled on every RBAC table';
  end if;

  if exists (
    select 1
    from pg_policy p
    where p.polrelid in (
      'public.admin_roles'::regclass,
      'public.admin_permissions'::regclass,
      'public.admin_role_permissions'::regclass,
      'public.admin_permission_overrides'::regclass,
      'public.admin_audit_logs'::regclass
    )
      and p.polcmd in ('*', 'a', 'w', 'd')
      and (0::oid = any(p.polroles) or p.polroles && array(
        select r.oid from pg_roles r where r.rolname in ('anon', 'authenticated')
      ))
  ) then
    raise exception 'RBAC RLS validation failed: client write policy exists on an RBAC table';
  end if;
end
$$;
